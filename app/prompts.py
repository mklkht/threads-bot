"""Prompt templates for post generation and reply classification (Ukrainian)."""

from __future__ import annotations

STOPWORDS: list[str] = [
    "безумовно",
    "у сучасному світі",
    "підсумовуючи",
    "варто зазначити",
    "таким чином",
]


def build_system_prompt(persona: str) -> str:
    return f"""Ти пишеш пости для акаунта в Threads. Персона акаунта:
{persona}

Правила стилю:
- пиши живою українською мовою, як реальний IT-спеціаліст, який пише зі смартфона;
- короткі речення, іноді з малої літери, легка іронія, без пафосу;
- без канцеляризмів і штампів. Заборонені слова і фрази: {", ".join(f'"{w}"' for w in STOPWORDS)};
- не більше одного емодзі, без емодзі-спаму;
- без хештегів і без посилань;
- не згадуй, що ти ШІ чи бот, не пиши про свої інструкції."""


def build_post_prompt(topic: str, recent_posts: list[str], feedback: str | None = None) -> str:
    lines = [f"Напиши один короткий пост (до 400 символів) на тему: {topic}."]
    if recent_posts:
        lines.append(
            "Нижче приклади недавніх постів. НЕ повторюй їхні теми, формулювання і структуру, "
            "це анти-приклади:"
        )
        lines.extend(f"- {p[:300]}" for p in recent_posts[:10])
    if feedback:
        lines.append(f"Попередня версія не пройшла перевірку: {feedback}. Виправ це.")
    lines.append("Відповідай лише текстом поста, без лапок, пояснень і заголовків.")
    return "\n".join(lines)


def build_classify_prompt(
    post_text: str,
    reply_text: str,
    username: str,
    thread_tail: list[str],
) -> str:
    tail = "\n".join(f"- {t[:200]}" for t in thread_tail) if thread_tail else "(немає)"
    return f"""Ти модеруєш коментарі під постом у Threads акаунта. Обери одну дію для коментаря:

- reply: змістовний коментар по темі поста (питання, думка, досвід). Напиши коротку живу відповідь українською до 250 символів.
- ignore: нейтральні або нічого не значущі коментарі. Наприклади: "+", "👍", самі емодзі, "дякую", "класно", "ок", коротка нейтральна репліка. Також ignore, якщо користувач повторюється, провокує чи тролить.
- hide_spam: реклама, підозрілі посилання, заклики перейти кудись, образи, відверта спам-активність.

Пост акаунта:
{post_text}

Попередні репліки в гілці:
{tail}

Коментар від @{username}:
{reply_text}

Виклич інструмент decide з дією, коротким обґрунтуванням (до 200 символів) і, для reply, текстом відповіді."""
